// The ban canaries: every entry of the root clippy.toml and every lint the workspace denies or forbids is
// shown to fire. canaries/bans/src/lib.rs holds one committed violation per entry, each line marked with the
// diagnostics clippy must report there (`// expect: ban:<path>` or `// expect: <lint>`). This script compiles
// it in a workspace generated from the root Cargo.toml — the same external dependencies with the same
// features, the same [workspace.lints], the same clippy.toml, the same Cargo.lock — and fails when:
//   - a marked line lacks a diagnostic it names, or carries one it does not name;
//   - an unmarked line carries any diagnostic;
//   - a clippy.toml entry or a denied or forbidden lint has no marker;
//   - clippy warns that a clippy.toml path does not refer to anything.
// The sqlx macro canaries need a database to expand: set DATABASE_URL (the wall does).
// Usage: node scripts/check-ban-canaries.mjs
import fs from 'node:fs';
import path from 'node:path';
import { captureAll, main, readText, report, Fail } from './_lib.mjs';
import { parseToml, tableText } from './_toml.mjs';

const repo = path.resolve(import.meta.dirname, '..');
const work = path.join(repo, 'target', 'ban-canaries');

function generate() {
  const cargo = readText(path.join(repo, 'Cargo.toml'));
  const deps = tableText(cargo, 'workspace.dependencies');
  const rust = tableText(cargo, 'workspace.lints.rust');
  const clippy = tableText(cargo, 'workspace.lints.clippy');
  if (!deps || !rust || !clippy) throw new Fail('Cargo.toml lacks [workspace.dependencies], [workspace.lints.rust] or [workspace.lints.clippy]');
  const external = deps
    .split('\n')
    .slice(1)
    .filter((l) => !/\bpath\s*=/.test(l))
    .join('\n');
  const manifest = [
    '# Generated by scripts/check-ban-canaries.mjs from the root Cargo.toml. Not committed.',
    '[package]',
    'name = "ban-canaries"',
    'version = "0.0.0"',
    'edition = "2024"',
    'publish = false',
    '',
    '[workspace]',
    '',
    rust,
    '',
    clippy,
    '',
    '[lints]',
    'workspace = true',
    '',
    '[dependencies]',
    external,
    '',
  ].join('\n');
  fs.rmSync(work, { recursive: true, force: true });
  fs.mkdirSync(path.join(work, 'src'), { recursive: true });
  fs.mkdirSync(path.join(work, 'sql'), { recursive: true });
  fs.writeFileSync(path.join(work, 'Cargo.toml'), manifest);
  fs.copyFileSync(path.join(repo, 'Cargo.lock'), path.join(work, 'Cargo.lock'));
  fs.copyFileSync(path.join(repo, 'clippy.toml'), path.join(work, 'clippy.toml'));
  fs.copyFileSync(path.join(repo, 'canaries', 'bans', 'src', 'lib.rs'), path.join(work, 'src', 'lib.rs'));
  fs.copyFileSync(path.join(repo, 'canaries', 'bans', 'sql', 'canary.sql'), path.join(work, 'sql', 'canary.sql'));
}

/** Every `// expect:` marker: line -> [expectation]. */
function markers() {
  const out = new Map();
  readText(path.join(repo, 'canaries', 'bans', 'src', 'lib.rs'))
    .split('\n')
    .forEach((line, i) => {
      const m = /\/\/ expect: (.+)$/.exec(line);
      if (m) out.set(i + 1, m[1].trim().split(/\s+/));
    });
  return out;
}

/** The line in the canary file a diagnostic belongs to: the first span in the file, macro call sites included. */
function lineOf(message) {
  const inFile = (span) => span && /(^|\/)src\/lib\.rs$/.test(span.file_name);
  for (const span of message.spans) {
    let s = span;
    while (s) {
      if (inFile(s)) return s.line_start;
      s = s.expansion?.span;
    }
  }
  return null;
}

function satisfies(diagnostic, expectation) {
  if (expectation.startsWith('ban:')) {
    const banned = expectation.slice(4);
    return (
      /^clippy::(disallowed_(methods|types|macros)|await_holding_invalid_type)$/.test(diagnostic.code) &&
      (diagnostic.text.includes(`\`${banned}\``) || diagnostic.notes.includes(banned))
    );
  }
  return diagnostic.code === expectation;
}

main(() => {
  if (!process.env.DATABASE_URL) throw new Fail('DATABASE_URL is not set: the sqlx macro canaries expand against a database (the wall provides one)');
  generate();
  const r = captureAll('cargo', ['clippy', '--offline', '--message-format=json', '--target-dir', path.join(repo, 'target')], {
    cwd: work,
    env: { SQLX_OFFLINE: 'false' },
  });
  const diagnostics = [];
  const invalidPaths = [];
  for (const line of r.stdout.split('\n')) {
    if (!line.startsWith('{')) continue;
    const msg = JSON.parse(line);
    if (msg.reason !== 'compiler-message') continue;
    const m = msg.message;
    if (/does not refer to/.test(m.message)) invalidPaths.push(m.message);
    if (!m.code?.code) {
      if (m.level === 'error' && !/^(could not compile|aborting)/.test(m.message)) diagnostics.push({ line: lineOf(m), code: `error: ${m.message}`, text: m.rendered ?? m.message, notes: '' });
      continue;
    }
    const notes = (m.children ?? []).map((c) => c.message).join('\n');
    diagnostics.push({ line: lineOf(m), code: m.code.code, text: m.message, notes });
  }
  if (r.status === 0) throw new Fail('clippy passed the canary crate: no ban or lint fired');

  const problems = [...invalidPaths.map((p) => `clippy.toml: ${p}`)];
  const expected = markers();
  const byLine = new Map();
  for (const d of diagnostics) {
    if (!byLine.has(d.line)) byLine.set(d.line, []);
    byLine.get(d.line).push(d);
  }
  for (const [line, found] of byLine) {
    if (!expected.has(line)) {
      for (const d of found) problems.push(`canaries/bans/src/lib.rs:${line}: unexpected ${d.code}: ${d.text.split('\n')[0]}`);
    }
  }
  for (const [line, wants] of expected) {
    const found = byLine.get(line) ?? [];
    for (const want of wants) {
      if (!found.some((d) => satisfies(d, want))) problems.push(`canaries/bans/src/lib.rs:${line}: ${want} did not fire`);
    }
    for (const d of found) {
      if (!wants.some((w) => satisfies(d, w))) problems.push(`canaries/bans/src/lib.rs:${line}: ${d.code} fired and is not expected: ${d.text.split('\n')[0]}`);
    }
  }

  // Coverage of the configuration: every clippy.toml path and every denied or forbidden lint has a marker.
  const marked = new Set([...expected.values()].flat());
  const clippyToml = parseToml(readText(path.join(repo, 'clippy.toml')), 'clippy.toml');
  for (const key of ['disallowed-methods', 'disallowed-types', 'disallowed-macros', 'await-holding-invalid-types']) {
    for (const entry of clippyToml[key] ?? []) {
      if (!marked.has(`ban:${entry.path}`)) problems.push(`clippy.toml ${key} ${entry.path}: no canary`);
    }
  }
  const cargo = parseToml(readText(path.join(repo, 'Cargo.toml')), 'Cargo.toml');
  for (const [tool, table] of Object.entries(cargo.workspace.lints)) {
    for (const [lint, setting] of Object.entries(table)) {
      const level = typeof setting === 'string' ? setting : setting.level;
      if (level !== 'deny' && level !== 'forbid') continue;
      const name = tool === 'rust' ? lint : `${tool}::${lint}`;
      if (name === 'warnings') {
        if (!marked.has('unused_variables')) problems.push('Cargo.toml warnings: no canary (unused_variables stands for it)');
        continue;
      }
      if (/^clippy::disallowed_/.test(name) || name === 'clippy::await_holding_invalid_type') continue; // proved by the ban: markers
      if (!marked.has(name)) problems.push(`Cargo.toml [workspace.lints.${tool}] ${lint}: no canary`);
    }
  }
  report(problems, 'ban canary problem(s)');
  console.log(`ban canaries: ${expected.size} marked lines, every clippy.toml entry and every denied or forbidden lint fired where marked, nothing else fired`);
});
